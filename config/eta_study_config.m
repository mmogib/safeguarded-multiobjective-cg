function cfg = eta_study_config(mcodeRoot,outputDir)
%ETA_STUDY_CONFIG Frozen mechanism-and-robustness study from exchange 035.

if nargin < 1
    mcodeRoot = fileparts(fileparts(mfilename('fullpath')));
end
if nargin < 2
    outputDir = fullfile(mcodeRoot,'data','results','eta_study');
end

grid = [0 0.01 0.03 0.1 0.3 1 3 10];
methods = {'TTCGP','TTCGH','TTCGL'};
jobs = struct('method','MOSD','mode','paper_r2','eta',0);
for eta = grid(2:end)
    for methodIndex = 1:numel(methods)
        jobs(end+1) = struct('method',methods{methodIndex}, ... %#ok<AGROW>
            'mode','paper_r2','eta',eta);
    end
end

cfg = struct('mcode_root',mcodeRoot,'output_dir',outputDir, ...
    'checkpoint_file',fullfile(outputDir,'eta_study_checkpoint.mat'), ...
    'zero_gate_file',fullfile(outputDir,'eta_zero_gate.mat'), ...
    'reproducibility_file', ...
        fullfile(outputDir,'eta_one_reproducibility.mat'), ...
    'study_version',1,'grid',grid,'jobs',jobs, ...
    'primary_problem_indices',[1 5 6 7 22 17 18 19 23 26 31 32 33 35 40], ...
    'natural_domain_indices',[31 32 33], ...
    'e2_problem_indices',1:5,'trials',1:100, ...
    'parallel_workers',8,'max_iter',5000, ...
    'invariant_abs_tol',1e-12,'invariant_rel_tol',1e-10);
end
