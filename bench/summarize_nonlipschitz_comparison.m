function output = summarize_nonlipschitz_comparison(rows,outputDir)
%SUMMARIZE_NONLIPSCHITZ_COMPARISON Export failure-aware E3 tables.

runs = make_run_table(rows);
profiles = nonlipschitz_performance_profiles(runs);
outcomes = make_outcomes(runs);
perProblem = make_per_problem(runs);
pairedWork = make_paired_work(runs);
exposure = make_exposure(runs);
cpu = make_cpu_summary(runs);
noDescent = make_no_descent(runs);
growth = make_growth_summary(runs);
frontMetrics = nonlipschitz_front_metrics(rows,outputDir);

writetable(runs,fullfile(outputDir,'e3_run_rows.csv'));
writetable(outcomes,fullfile(outputDir,'e3_outcomes.csv'));
writetable(perProblem,fullfile(outputDir,'e3_per_problem.csv'));
writetable(pairedWork,fullfile(outputDir,'e3_paired_work.csv'));
writetable(profiles.ratios,fullfile(outputDir,'e3_profile_ratios.csv'));
writetable(profiles.curves,fullfile(outputDir,'e3_profile_curves.csv'));
writetable(exposure,fullfile(outputDir,'e3_exposure_conditioned.csv'));
writetable(cpu,fullfile(outputDir,'e3_cpu_descriptive.csv'));
writetable(noDescent,fullfile(outputDir,'e3_no_descent_events.csv'));
writetable(growth,fullfile(outputDir,'e3_direction_growth.csv'));

output = struct('runs',runs,'outcomes',outcomes,'per_problem',perProblem, ...
    'paired_work',pairedWork,'profile_ratios',profiles.ratios, ...
    'profile_curves',profiles.curves,'exposure',exposure,'cpu',cpu, ...
    'no_descent',noDescent,'growth',growth,'front_metrics',frontMetrics);
end

function runs = make_run_table(rows)
runs = table(string({rows.set_name})',string({rows.problem})', ...
    [rows.problem_index]',string({rows.method})',[rows.trial]', ...
    string({rows.gate_status})',string({rows.status})', ...
    [rows.iterations]',[rows.theta]',[rows.v_norm]', ...
    [rows.steepest_directional_value]',[rows.vector_F]',[rows.vector_J]', ...
    [rows.component_F]',[rows.component_J]',[rows.line_search_trials]', ...
    [rows.qp_solves]',[rows.wall_time]',[rows.evaluation_time]', ...
    [rows.qp_time]',[rows.descent_violations]',[rows.no_descent_iteration]', ...
    [rows.no_descent_value]',[rows.no_descent_steepest_value]', ...
    [rows.no_descent_steepest_norm_squared]',[rows.qp_failures]', ...
    [rows.nonfinite_events]',[rows.max_direction_norm]', ...
    [rows.max_direction_over_v_norm]',[rows.max_abs_raw_beta]', ...
    [rows.max_lindu_correction]',[rows.s_0]',[rows.s_min_post0]', ...
    [rows.s_end]',[rows.d_0]',[rows.d_min_post0]',[rows.d_end]', ...
    [rows.chi_0]',[rows.chi_max_post0]',[rows.chi_end]', ...
    [rows.s_contraction]',[rows.d_contraction]', ...
    [rows.accepted_post0_count]',[rows.regular_exact_hits]', ...
    [rows.degenerate_zeros]',[rows.inner_stationary]', ...
    [rows.unavailable_proxies]', ...
    'VariableNames',{'set_name','problem','problem_index','method','trial', ...
    'gate_status','status','iterations','theta','v_norm', ...
    'steepest_directional_value','vector_F','vector_J','component_F', ...
    'component_J','line_search_trials','qp_solves','wall_time', ...
    'evaluation_time','qp_time','descent_violations', ...
    'no_descent_iteration','no_descent_value','no_descent_steepest_value', ...
    'no_descent_steepest_norm_squared','qp_failures','nonfinite_events', ...
    'max_direction_norm','max_direction_over_v_norm','max_abs_raw_beta', ...
    'max_lindu_correction','s_0','s_min_post0','s_end','d_0', ...
    'd_min_post0','d_end','chi_0','chi_max_post0','chi_end', ...
    's_contraction','d_contraction','accepted_post0_count', ...
    'regular_exact_hits','degenerate_zeros','inner_stationary', ...
    'unavailable_proxies'});
runs.exposure_stratum = arrayfun(@exposure_stratum,runs.problem);
runs.log10_d_min_post0 = log10(runs.d_min_post0);
runs.log10_chi_max_post0 = log10(runs.chi_max_post0);
end

function stratum = exposure_stratum(problem)
if startsWith(problem,"E2-")
    stratum = "primary_e2";
elseif ismember(problem,["NL10-6","NL10-7"])
    stratum = "strong";
elseif ismember(problem,["NL10-5","NL10-8"])
    stratum = "moderate";
elseif ismember(problem,["NL10-2","NL10-9","NL10-10"])
    stratum = "limited";
else
    stratum = "smooth_control";
end
end

function outcomes = make_outcomes(runs)
[group,method,problem,stratum,gate,status] = findgroups(runs.method, ...
    runs.problem,runs.exposure_stratum,runs.gate_status,runs.status);
count = splitapply(@numel,runs.trial,group);
outcomes = table(method,problem,stratum,gate,status,count, ...
    'VariableNames',{'method','problem','exposure_stratum','gate_status', ...
    'status','runs'});
end

function summary = make_per_problem(runs)
keys = unique(runs(:,{'method','problem','exposure_stratum'}),'rows','stable');
summary = table();
for k = 1:height(keys)
    block = runs(runs.method==keys.method(k) & runs.problem==keys.problem(k),:);
    success = block.status == "converged";
    summary = [summary; table(keys.method(k),keys.problem(k), ...
        keys.exposure_stratum(k),height(block),sum(success), ...
        conditional_median(block.iterations,success), ...
        conditional_median(block.component_F,success), ...
        conditional_median(block.component_J,success), ...
        conditional_median(block.line_search_trials,success), ...
        conditional_median(block.qp_solves,success), ...
        median(block.d_min_post0,'omitnan'), ...
        median(block.chi_max_post0,'omitnan'), ...
        'VariableNames',{'method','problem','exposure_stratum','runs', ...
        'converged','median_iterations','median_component_F', ...
        'median_component_J','median_line_search_trials','median_qp_solves', ...
        'median_d_min_post0','median_chi_max_post0'})]; %#ok<AGROW>
end
end

function paired = make_paired_work(runs)
methods = unique(runs.method,'stable');
metrics = {'iterations','component_F','component_J','line_search_trials','qp_solves'};
paired = table();
for leftIndex = 1:numel(methods)-1
    for rightIndex = leftIndex+1:numel(methods)
        left = sortrows(runs(runs.method==methods(leftIndex),:),{'problem','trial'});
        right = sortrows(runs(runs.method==methods(rightIndex),:),{'problem','trial'});
        if height(left) ~= height(right) || any(left.problem~=right.problem) || ...
                any(left.trial~=right.trial)
            error('mcode:UnpairedNonLipschitzComparison','E3 task keys differ.');
        end
        slices = ["all";unique(left.problem,'stable')];
        for sliceIndex = 1:numel(slices)
            if slices(sliceIndex)=="all"
                use = true(height(left),1);
            else
                use = left.problem==slices(sliceIndex);
            end
            for metricIndex = 1:numel(metrics)
                paired = [paired; paired_row(left(use,:),right(use,:), ...
                    methods(leftIndex),methods(rightIndex),metrics{metricIndex}, ...
                    slices(sliceIndex))]; %#ok<AGROW>
            end
        end
    end
end
end

function row = paired_row(left,right,leftMethod,rightMethod,metric,slice)
leftSuccess = left.status=="converged";
rightSuccess = right.status=="converged";
both = leftSuccess & rightSuccess;
if any(both)
    ratios = left.(metric)(both)./right.(metric)(both);
    geomean = exp(mean(log(ratios)));
    wins = sum(ratios<1); ties = sum(ratios==1); losses = sum(ratios>1);
else
    geomean = NaN; wins = 0; ties = 0; losses = 0;
end
row = table(leftMethod,rightMethod,string(slice),string(metric),height(left), ...
    sum(leftSuccess),sum(rightSuccess),sum(both), ...
    sum(leftSuccess & ~rightSuccess),sum(~leftSuccess & rightSuccess), ...
    sum(~leftSuccess & ~rightSuccess),geomean,wins,ties,losses, ...
    'VariableNames',{'left_method','right_method','slice','metric','tasks', ...
    'left_successes','right_successes','paired_successes','left_only_success', ...
    'right_only_success','both_failed','geomean_left_over_right','wins', ...
    'ties','losses'});
end

function exposure = make_exposure(runs)
bands = 10.^(-(1:8));
keys = unique(runs(:,{'method','problem','exposure_stratum','gate_status'}), ...
    'rows','stable');
exposure = table();
for k = 1:height(keys)
    block = runs(runs.method==keys.method(k) & runs.problem==keys.problem(k) & ...
        runs.gate_status==keys.gate_status(k),:);
    for threshold = bands
        exposed = block.d_min_post0 <= threshold;
        success = exposed & block.status=="converged";
        n = sum(exposed);
        if n == 0, successRate = NaN; else, successRate = sum(success)/n; end
        exposure = [exposure; table(keys.method(k),keys.problem(k), ...
            keys.exposure_stratum(k),keys.gate_status(k),threshold,n, ...
            sum(success),successRate,conditional_median(block.iterations,success), ...
            conditional_median(block.component_F,success), ...
            conditional_median(block.component_J,success), ...
            conditional_median(block.line_search_trials,success), ...
            conditional_median(block.qp_solves,success), ...
            'VariableNames',{'method','problem','exposure_stratum', ...
            'gate_status','threshold','runs_at_or_below','converged', ...
            'success_rate','median_iterations','median_component_F', ...
            'median_component_J','median_line_search_trials', ...
            'median_qp_solves'})]; %#ok<AGROW>
    end
end
end

function cpu = make_cpu_summary(runs)
keys = unique(runs(:,{'method','problem'}),'rows','stable');
cpu = table();
for k = 1:height(keys)
    block = runs(runs.method==keys.method(k) & runs.problem==keys.problem(k),:);
    success = block.status=="converged";
    cpu = [cpu; table(keys.method(k),keys.problem(k),sum(success), ...
        conditional_median(block.wall_time,success), ...
        conditional_median(block.evaluation_time,success), ...
        conditional_median(block.qp_time,success), ...
        'VariableNames',{'method','problem','converged', ...
        'median_wall_time_descriptive','median_evaluation_time_descriptive', ...
        'median_qp_time_descriptive'})]; %#ok<AGROW>
end
end

function events = make_no_descent(runs)
use = runs.status=="no_descent";
events = runs(use,{'method','problem','trial','exposure_stratum','gate_status', ...
    'd_min_post0','chi_max_post0','no_descent_iteration','no_descent_value', ...
    'no_descent_steepest_value','no_descent_steepest_norm_squared', ...
    'max_direction_norm','max_direction_over_v_norm','max_abs_raw_beta'});
end

function growth = make_growth_summary(runs)
keys = unique(runs(:,{'method','problem'}),'rows','stable');
growth = table();
for k = 1:height(keys)
    block = runs(runs.method==keys.method(k) & runs.problem==keys.problem(k),:);
    growth = [growth; table(keys.method(k),keys.problem(k), ...
        median(block.max_direction_norm,'omitnan'), ...
        max(block.max_direction_norm,[],'omitnan'), ...
        median(block.max_direction_over_v_norm,'omitnan'), ...
        max(block.max_direction_over_v_norm,[],'omitnan'), ...
        median(block.max_abs_raw_beta,'omitnan'), ...
        max(block.max_abs_raw_beta,[],'omitnan'), ...
        'VariableNames',{'method','problem','median_max_direction_norm', ...
        'maximum_direction_norm','median_max_direction_over_v_norm', ...
        'maximum_direction_over_v_norm','median_max_abs_raw_beta', ...
        'maximum_abs_raw_beta'})]; %#ok<AGROW>
end
end

function value = conditional_median(values,use)
if any(use), value = median(values(use),'omitnan'); else, value = NaN; end
end
