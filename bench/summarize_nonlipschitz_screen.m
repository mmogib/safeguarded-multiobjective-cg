function output = summarize_nonlipschitz_screen(rows,gateRows,projectionRows,outputDir)
%SUMMARIZE_NONLIPSCHITZ_SCREEN Export per-problem/method E1 and gate summaries.

summary = make_summary(rows);
bands = make_band_summary(rows);
gate = make_gate_summary(gateRows);
projection = struct2table(projectionRows,'AsArray',true);
runRows = make_run_table(rows);
paired = make_paired_table(runRows);

writetable(summary,fullfile(outputDir,'e1_summary.csv'));
writetable(bands,fullfile(outputDir,'e1_band_summary.csv'));
writetable(runRows,fullfile(outputDir,'e1_run_rows.csv'));
writetable(paired,fullfile(outputDir,'e1_paired_by_start.csv'));
writetable(gate,fullfile(outputDir,'accessibility_gate_summary.csv'));
writetable(struct2table(gateRows,'AsArray',true), ...
    fullfile(outputDir,'accessibility_gate_rows.csv'));
writetable(projection,fullfile(outputDir,'e2_projection_checks.csv'));
output = struct('summary',summary,'bands',bands,'runs',runRows, ...
    'paired',paired,'gate',gate,'projection',projection);
end

function summary = make_summary(rows)
problems = unique(string({rows.problem}),'stable');
methods = unique(string({rows.method}),'stable');
records = struct('set_name',{},'problem',{},'method',{},'runs',{}, ...
    'converged',{},'line_search_failed',{},'max_iter',{}, ...
    'd_min_min',{},'d_min_q25',{},'d_min_median',{},'d_min_q75',{}, ...
    'd_min_max',{},'d_min_log10_q25',{},'d_min_log10_median',{}, ...
    'd_min_log10_q75',{},'chi_max_min',{},'chi_max_q25',{}, ...
    'chi_max_median',{},'chi_max_q75',{},'chi_max_max',{}, ...
    'chi_max_log10_q25',{},'chi_max_log10_median',{}, ...
    'chi_max_log10_q75',{},'d_contraction_min',{}, ...
    'd_contraction_q25',{},'d_contraction_median',{}, ...
    'd_contraction_q75',{},'d_contraction_max',{}, ...
    's_contraction_min',{},'s_contraction_q25',{}, ...
    's_contraction_median',{},'s_contraction_q75',{}, ...
    's_contraction_max',{}, ...
    'regular_exact_hits',{},'degenerate_zeros',{},'inner_stationary',{}, ...
    'accepted_post0_count',{});
for problemIndex = 1:numel(problems)
    p = problems(problemIndex);
    for methodIndex = 1:numel(methods)
        m = methods(methodIndex);
        mask = strcmp({rows.problem},p) & strcmp({rows.method},m);
        block = rows(mask);
        if isempty(block), continue, end
        dmin = [block.d_min_post0];
        chimax = [block.chi_max_post0];
        dcontraction = [block.d_contraction];
        scontraction = [block.s_contraction];
        records(end+1) = struct('set_name',block(1).set_name,'problem',char(p), ...
            'method',char(m),'runs',numel(block), ...
            'converged',sum(strcmp({block.status},'converged')), ...
            'line_search_failed',sum(strcmp({block.status},'line_search_failed')), ...
            'max_iter',sum(strcmp({block.status},'max_iter')), ...
            'd_min_min',min_omitnan(dmin),'d_min_q25',percentile(dmin,25), ...
            'd_min_median',percentile(dmin,50),'d_min_q75',percentile(dmin,75), ...
            'd_min_max',max_omitnan(dmin), ...
            'd_min_log10_q25',percentile(log10(dmin),25), ...
            'd_min_log10_median',percentile(log10(dmin),50), ...
            'd_min_log10_q75',percentile(log10(dmin),75), ...
            'chi_max_min',min_omitnan(chimax), ...
            'chi_max_q25',percentile(chimax,25), ...
            'chi_max_median',percentile(chimax,50), ...
            'chi_max_q75',percentile(chimax,75), ...
            'chi_max_max',max_omitnan(chimax), ...
            'chi_max_log10_q25',percentile(log10(chimax),25), ...
            'chi_max_log10_median',percentile(log10(chimax),50), ...
            'chi_max_log10_q75',percentile(log10(chimax),75), ...
            'd_contraction_min',min_omitnan(dcontraction), ...
            'd_contraction_q25',percentile(dcontraction,25), ...
            'd_contraction_median',percentile(dcontraction,50), ...
            'd_contraction_q75',percentile(dcontraction,75), ...
            'd_contraction_max',max_omitnan(dcontraction), ...
            's_contraction_min',min_omitnan(scontraction), ...
            's_contraction_q25',percentile(scontraction,25), ...
            's_contraction_median',percentile(scontraction,50), ...
            's_contraction_q75',percentile(scontraction,75), ...
            's_contraction_max',max_omitnan(scontraction), ...
            'regular_exact_hits',sum([block.regular_exact_hits]), ...
            'degenerate_zeros',sum([block.degenerate_zeros]), ...
            'inner_stationary',sum([block.inner_stationary]), ...
            'accepted_post0_count',sum([block.accepted_post0_count])); %#ok<AGROW>
    end
end
summary = struct2table(records);
end

function runs = make_run_table(rows)
runs = table(string({rows.set_name})',string({rows.problem})', ...
    [rows.problem_index]',string({rows.method})',[rows.trial]', ...
    string({rows.status})',[rows.iterations]',[rows.vector_F]', ...
    [rows.vector_J]',[rows.s_0]',[rows.s_min_post0]',[rows.s_end]', ...
    [rows.d_0]',[rows.d_min_post0]',[rows.d_end]',[rows.chi_0]', ...
    [rows.chi_max_post0]',[rows.chi_end]',[rows.s_contraction]', ...
    [rows.d_contraction]',[rows.accepted_post0_count]', ...
    [rows.regular_exact_hits]',[rows.degenerate_zeros]', ...
    [rows.inner_stationary]',[rows.unavailable_proxies]', ...
    'VariableNames',{'set_name','problem','problem_index','method','trial', ...
    'status','iterations','vector_F','vector_J','s_0','s_min_post0', ...
    's_end','d_0','d_min_post0','d_end','chi_0','chi_max_post0', ...
    'chi_end','s_contraction','d_contraction','accepted_post0_count', ...
    'regular_exact_hits','degenerate_zeros','inner_stationary', ...
    'unavailable_proxies'});
runs.log10_s_min_post0 = log10(runs.s_min_post0);
runs.log10_d_min_post0 = log10(runs.d_min_post0);
runs.log10_chi_max_post0 = log10(runs.chi_max_post0);
end

function paired = make_paired_table(runs)
paired = unique(runs(:,{'set_name','problem','trial'}),'rows','stable');
methods = {'TTCGP','TTCGH','TTCGL'};
for methodIndex = 1:numel(methods)
    method = methods{methodIndex};
    n = height(paired);
    status = strings(n,1);
    iterations = NaN(n,1);
    dmin = NaN(n,1);
    chimax = NaN(n,1);
    dcontraction = NaN(n,1);
    scontraction = NaN(n,1);
    for rowIndex = 1:n
        match = runs.problem == paired.problem(rowIndex) & ...
            runs.trial == paired.trial(rowIndex) & runs.method == method;
        if any(match)
            status(rowIndex) = runs.status(find(match,1));
            iterations(rowIndex) = runs.iterations(find(match,1));
            dmin(rowIndex) = runs.d_min_post0(find(match,1));
            chimax(rowIndex) = runs.chi_max_post0(find(match,1));
            dcontraction(rowIndex) = runs.d_contraction(find(match,1));
            scontraction(rowIndex) = runs.s_contraction(find(match,1));
        end
    end
    paired.(['status_' method]) = status;
    paired.(['iterations_' method]) = iterations;
    paired.(['d_min_post0_' method]) = dmin;
    paired.(['chi_max_post0_' method]) = chimax;
    paired.(['d_contraction_' method]) = dcontraction;
    paired.(['s_contraction_' method]) = scontraction;
end
end

function bands = make_band_summary(rows)
distanceBands = 10.^(-(1:8));
chiBands = 10.^((1:8)/2);
problems = unique(string({rows.problem}),'stable');
methods = unique(string({rows.method}),'stable');
records = struct('set_name',{},'problem',{},'method',{},'metric',{}, ...
    'threshold',{},'count',{},'denominator',{},'fraction',{});
for problemIndex = 1:numel(problems)
    p = problems(problemIndex);
    for methodIndex = 1:numel(methods)
        m = methods(methodIndex);
        block = rows(strcmp({rows.problem},p) & strcmp({rows.method},m));
        if isempty(block), continue, end
        denominator = sum([block.accepted_post0_count]);
        metrics = {'s','d','chi'};
        thresholds = {distanceBands,distanceBands,chiBands};
        fields = {'s_band_counts','d_band_counts','chi_band_counts'};
        for metric = 1:3
            counts = sum(vertcat(block.(fields{metric})),1);
            for band = 1:8
                records(end+1) = struct('set_name',block(1).set_name, ...
                    'problem',char(p),'method',char(m),'metric',metrics{metric}, ...
                    'threshold',thresholds{metric}(band),'count',counts(band), ...
                    'denominator',denominator,'fraction',safe_divide( ...
                    counts(band),denominator)); %#ok<AGROW>
            end
        end
    end
end
bands = struct2table(records);
end

function gate = make_gate_summary(rows)
problems = unique(string({rows.problem}),'stable');
records = struct('problem',{},'starts',{},'certified_accessible',{}, ...
    'unresolved',{},'certified_inaccessible',{});
for problemIndex = 1:numel(problems)
    p = problems(problemIndex);
    block = rows(strcmp({rows.problem},p));
    records(end+1) = struct('problem',char(p),'starts',numel(block), ...
        'certified_accessible',sum(strcmp({block.status},'certified_accessible')), ...
        'unresolved',sum(strcmp({block.status},'unresolved')), ...
        'certified_inaccessible',sum(strcmp({block.status}, ...
        'certified_inaccessible'))); %#ok<AGROW>
end
gate = struct2table(records);
end

function value = percentile(values,p)
values = values(~isnan(values));
if isempty(values), value = NaN; else, value = prctile(values,p); end
end

function value = min_omitnan(values)
values = values(~isnan(values));
if isempty(values), value = NaN; else, value = min(values); end
end

function value = max_omitnan(values)
values = values(~isnan(values));
if isempty(values), value = NaN; else, value = max(values); end
end

function value = safe_divide(numerator,denominator)
if denominator == 0, value = NaN; else, value = numerator/denominator; end
end
