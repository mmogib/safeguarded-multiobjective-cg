function write_full_campaign_front_quality(quality,outputDir)
%WRITE_FULL_CAMPAIGN_FRONT_QUALITY Write front-quality reduction artifacts.

if ~isfolder(outputDir), mkdir(outputDir); end
writetable(quality.per_problem, ...
    fullfile(outputDir,'front_quality_per_problem.csv'));
writetable(quality.coverage, ...
    fullfile(outputDir,'front_coverage_per_problem.csv'));
writetable(coverage_matrices(quality.coverage), ...
    fullfile(outputDir,'front_coverage_matrices.csv'));
writetable(quality.coverage_aggregate, ...
    fullfile(outputDir,'front_coverage_aggregate.csv'));
writetable(aggregate_coverage_matrix(quality.coverage_aggregate, ...
    'mean_coverage'),fullfile(outputDir,'front_coverage_mean_matrix.csv'));
writetable(aggregate_coverage_matrix(quality.coverage_aggregate, ...
    'median_coverage'), ...
    fullfile(outputDir,'front_coverage_median_matrix.csv'));
writetable(quality.pairwise_purity, ...
    fullfile(outputDir,'front_pairwise_purity_per_problem.csv'));
writetable(quality.pairwise_purity_aggregate, ...
    fullfile(outputDir,'front_pairwise_purity_aggregate.csv'));
writetable(quality.aggregate, ...
    fullfile(outputDir,'front_quality_aggregate.csv'));
write_definitions(fullfile(outputDir,'front_quality_definitions.txt'));
save(fullfile(outputDir,'front_quality_report.mat'),'quality','-v7.3');
end

function matrix = aggregate_coverage_matrix(rows,valueName)
methods = unique(rows.source_method,'stable');
values = NaN(numel(methods));
for source = 1:numel(methods)
    for target = 1:numel(methods)
        selected = rows.source_method==methods(source) & ...
            rows.target_method==methods(target);
        values(source,target) = rows.(valueName)(selected);
    end
end
names = matlab.lang.makeValidName(cellstr("to_"+methods));
matrix = [table(methods,'VariableNames',{'source_method'}), ...
    array2table(values,'VariableNames',names)];
end

function matrices = coverage_matrices(rows)
problems = unique(rows.problem,'stable');
methods = unique(rows.source_method,'stable');
matrices = table();
for p = 1:numel(problems)
    for source = 1:numel(methods)
        selected = rows.problem==problems(p) & ...
            rows.source_method==methods(source);
        values = NaN(1,numel(methods));
        for target = 1:numel(methods)
            row = selected & rows.target_method==methods(target);
            values(target) = rows.coverage(row);
        end
        prefix = table(problems(p),methods(source), ...
            'VariableNames',{'problem','source_method'});
        names = matlab.lang.makeValidName(cellstr("to_"+methods));
        matrices = [matrices;[prefix,array2table(values, ...
            'VariableNames',names)]]; %#ok<AGROW>
    end
end
end

function write_definitions(path)
text = [ ...
    "Front construction" newline ...
    "For each problem and method, F_(p,s) is the set of unique, " ...
    "nondominated final objective vectors from converged runs. " ...
    "Dominance and equality are evaluated exactly in the stored " ...
    "objective values; no tolerance is introduced." newline newline ...
    "Coverage (Zitzler--Thiele, equation (7))" newline ...
    "C(X',X'') is the fraction of points in X'' dominated-or-equalled " ...
    "by at least one point in X'. Both directed values are retained. " ...
    "Coverage is undefined when X'' is empty and is zero when only X' " ...
    "is empty. Coverage means and medians use only problems on which " ...
    "both methods returned a non-empty front." newline newline ...
    "Purity (Custodio et al., section 5.3.2)" newline ...
    "The pooled reference F_p is the nondominated subset of the union " ...
    "of all seven method fronts. Purity is |F_(p,s) intersect F_p| " ...
    "/ |F_(p,s)|. Because the source warns that purity depends on the " ...
    "solvers included, pairwise purities are also reported using the " ...
    "same definition with each pair's pooled reference." newline newline ...
    "Gamma and Delta (Custodio et al., equations (5.1)--(5.2))" newline ...
    "For each objective j, method values are sorted increasingly and " ...
    "the common lower and upper extremes are the minimum and maximum " ...
    "coordinates of F_p. The gaps delta_(i,j) include both endpoint " ...
    "gaps. Gamma is the largest gap over all objectives. Delta is the " ...
    "largest, over objectives, of [endpoint gaps plus the sum of " ...
    "absolute deviations of internal gaps from their mean] divided by " ...
    "[endpoint gaps plus (N-1) times that mean]. Delta is undefined for " ...
    "a singleton or empty method front. A zero-range objective " ...
    "contributes zero to Delta. The outside_reference_range flag marks " ...
    "a method front not bracketed by the pooled extremes. Because the " ...
    "source then cannot index those extremes as endpoints of an " ...
    "increasing sequence, Gamma and Delta are reported as undefined and " ...
    "that problem is excluded from spread comparisons." newline newline ...
    "Aggregation" newline ...
    "Coverage and purity means and medians weight problems equally, " ...
    "not points. Purity means and medians use only problems on which " ...
    "every reported method returned a non-empty front. Spread comparisons " ...
    "use only problems on which every reported method returned a non-empty " ...
    "front. Raw Gamma is not averaged across problems because it " ...
    "has objective units. Gamma and Delta are aggregated through the " ...
    "Custodio performance ratio: each value divided by the best finite " ...
    "value on that problem. If the best value is zero, zero values get " ...
    "ratio one and positive values get infinity. An unavailable method " ...
    "value gets infinity when another method has a finite value; a " ...
    "problem unavailable to every method is excluded." newline newline ...
    "Excluded measures" newline ...
    "Origin-box hypervolume is omitted because these are minimization " ...
    "problems: the Zitzler--Thiele origin construction rewards a worse " ...
    "point with a larger box, and repairing it requires an arbitrary " ...
    "reference choice. IGD is omitted because no paper in the " ...
    "authoritative library supplied a verified formula." newline];
file = fopen(path,'w','n','UTF-8');
if file < 0, error('frontquality:WriteFailed','Cannot write %s.',path); end
cleanup = onCleanup(@() fclose(file)); %#ok<NASGU>
fprintf(file,'%s',join(text,''));
end
