function contract = full_campaign_retention_contract()
%FULL_CAMPAIGN_RETENTION_CONTRACT baseline_v1 plus three-tier diagnostics.

contract = campaignstore.baseline_retention_contract();
contract.runs = [contract.runs,{'tier','set_name','problem','problem_index', ...
    'method','mode','eta_bar','theorem_compatible','unbounded_level_set', ...
    'natural_domain','exposure_stratum','tier3_primary'}];
contract.iterations = [contract.iterations,{'steepest_directional_value', ...
    'directional_value','descent_gap','descent_tolerance', ...
    'descent_bound_holds'}];
contract.extras.line_trials = {'run_key','k','trial','alpha','accepted', ...
    'q','g','phi'};
commonTier2 = {'run_key','k','argument_id','r','d','distance_kind', ...
    'status','chi'};
contract.extras.tier2_accepted_exposure = commonTier2;
contract.extras.tier2_line_trial_exposure = [commonTier2, ...
    {'trial','alpha','accepted'}];
commonTier3 = {'run_key','k','argument_id','r','d','distance_kind', ...
    'status','actual_exposure','inverse_t_envelope'};
contract.extras.tier3_accepted_exposure = commonTier3;
contract.extras.tier3_line_trial_exposure = [commonTier3, ...
    {'trial','alpha','accepted'}];
end

