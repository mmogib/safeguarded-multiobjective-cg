function args = nonlipschitz_arguments(prob)
%NONLIPSCHITZ_ARGUMENTS Singular-kernel metadata independent of Evaluator.

if strcmp(prob.set_name,'E2')
    args = e2_arguments(prob.local_index);
elseif ismember(prob.set_name,{'NL10','NC10'})
    args = nl10_arguments(prob.local_index);
else
    error('mcode:InvalidArgumentMetadataProblem', ...
        'No singular-argument metadata for set %s.',prob.set_name);
end
end

function args = e2_arguments(d)
switch d
    case 1
        args = affine_arg('h',[1 2],[0;1],0);
    case 2
        args = make_arg('h',[1 2],@(x) x(2)-x(1)^2, ...
            @(x) [-2*x(1);1],'first_order_proxy', ...
            @(x) abs(x(2)-x(1)^2)/norm([-2*x(1);1]),[0;0],[0;1], ...
            {component(@(u) [u;u.^2],[-20 20])});
    case 3
        args = make_arg('h',[1 2],@(x) x(2)-0.5*sin(x(1)), ...
            @(x) [-0.5*cos(x(1));1],'first_order_proxy', ...
            @(x) abs(x(2)-0.5*sin(x(1)))/norm([-0.5*cos(x(1));1]), ...
            [0;0],[0;1],{component(@(u) [u;0.5*sin(u)],[-20 20])});
    case 4
        args = affine_arg('h',[1 2],[0;1],0);
    case 5
        args = make_arg('h',[1 2 3], ...
            @(x) x(2)-0.25*sum(x(3:10).^2), ...
            @(x) [0;1;-0.5*x(3:10)],'first_order_proxy', ...
            @(x) abs(x(2)-0.25*sum(x(3:10).^2))/ ...
                norm([0;1;-0.5*x(3:10)]),zeros(10,1),unit(10,2),{});
end
end

function args = nl10_arguments(d)
switch d
    case 1
        args = [affine_arg('f1_t1',1,[1;0],0), ...
                affine_arg('f1_t2',1,[0;1],-1), ...
                affine_arg('f2_t1',2,[1;0],-2), ...
                affine_arg('f2_t2',2,[0;1],1)];
    case 2
        args = [affine_arg('f1_t1',1,[1;1],0), ...
                affine_arg('f1_t2',1,[1;0],-1), ...
                affine_arg('f2_t1',2,[1;-1],0), ...
                affine_arg('f2_t2',2,[0;1],2)];
    case 3
        args = [affine_arg('f1_t1',1,[2;-1],0), ...
                affine_arg('f1_t2',1,[1;0],1), ...
                affine_arg('f2_t1',2,[1;3],-1), ...
                affine_arg('f2_t2',2,[0;1],-2)];
    case 4
        args = [affine_arg('f1_t1',1,[1;0],-2), ...
                affine_arg('f1_t2',1,[0;1],1), ...
                affine_arg('f2_t1',2,[1;0],-4), ...
                affine_arg('f2_t2',2,[0;1],-3)];
    case 5
        args = [product_arg('f1_t1',1,0,0), ...
                affine_arg('f1_t2',1,[1;0],-1), ...
                product_arg('f2_t1',2,1,-2), ...
                affine_arg('f2_t2',2,[0;1],-2)];
    case 6
        args = [circle_arg('f1_t1',1,[0;0],1), ...
                circle_arg('f2_t1',2,[3;4],2)];
    case 7
        args = [affine_arg('f1_t1',1,[1;-2],1), ...
                affine_arg('f2_t1',2,[3;1],-4)];
    case 8
        args = [affine_arg('f1_t1',1,[1;1],-2), ...
                affine_arg('f1_t2',1,[1;0],-1), ...
                affine_arg('f2_t1',2,[2;-1],3), ...
                affine_arg('f2_t2',2,[0;1],-4)];
    case 9
        args = [parabola_arg('f1_t1',1,1), ...
                affine_arg('f1_t2',1,[1;0],1), ...
                parabola_arg('f2_t1',2,2), ...
                affine_arg('f2_t2',2,[0;1],-3)];
    case 10
        args = [affine_arg('f1_t1',1,[1;0],0), ...
                affine_arg('f1_t2',1,[1;1],0), ...
                affine_arg('f2_t1',2,[0;1],-5), ...
                affine_arg('f2_t2',2,[1;-1],1)];
end
end

function a = affine_arg(id,rows,normal,offset)
normalNorm = norm(normal);
base = -offset*normal/(normalNorm^2);
tangent = [-normal(2);normal(1)]/normalNorm;
a = make_arg(id,rows,@(x) normal'*x+offset,@(~) normal,'exact', ...
    @(x) abs(normal'*x+offset)/normalNorm,base,normal/normalNorm, ...
    {component(@(u) base+u*tangent,[-20 20])});
end

function a = product_arg(id,rows,shift1,shift2)
value = @(x) (x(1)-shift1)*(x(2)-shift2);
gradient = @(x) [x(2)-shift2;x(1)-shift1];
distance = @(x) min(abs(x(1)-shift1),abs(x(2)-shift2));
anchor = [shift1;shift2+1];
components = {component(@(u) [shift1;u],[-20 20]), ...
              component(@(u) [u;shift2],[-20 20])};
a = make_arg(id,rows,value,gradient,'exact',distance,anchor,[1;0],components);
end

function a = circle_arg(id,rows,center,radius)
value = @(x) sum((x-center).^2)-radius^2;
gradient = @(x) 2*(x-center);
distance = @(x) abs(norm(x-center)-radius);
anchor = center+[radius;0];
map = @(theta) center+radius*[cos(theta);sin(theta)];
a = make_arg(id,rows,value,gradient,'exact',distance,anchor,[1;0], ...
    {component(map,[0 2*pi])});
end

function a = parabola_arg(id,rows,orientation)
if orientation == 1
    value = @(x) x(1)^2-x(2);
    gradient = @(x) [2*x(1);-1];
    distance = @(x) abs(value(x))/norm(gradient(x));
    anchor = [0;0]; normal = [0;-1];
    map = @(u) [u;u.^2];
else
    value = @(x) x(2)^2-x(1)+2;
    gradient = @(x) [-1;2*x(2)];
    distance = @(x) abs(value(x))/norm(gradient(x));
    anchor = [2;0]; normal = [-1;0];
    map = @(u) [u.^2+2;u];
end
a = make_arg(id,rows,value,gradient,'first_order_proxy',distance, ...
    anchor,normal,{component(map,[-20 20])});
end

function a = make_arg(id,rows,value,gradient,distanceKind,distance, ...
    anchor,normal,components)
a = struct('argument_id',id,'objective_rows',rows,'value',value, ...
    'gradient',gradient,'distance_kind',distanceKind,'distance',distance, ...
    'regular_zero_test',@(x) value(x)==0 && norm(gradient(x))>0, ...
    'validation_anchor',anchor,'validation_normal',normal/norm(normal), ...
    'witness_components',{components});
end

function c = component(map,bounds)
c = struct('map',map,'bounds',bounds);
end

function e = unit(n,k)
e = zeros(n,1); e(k) = 1;
end
