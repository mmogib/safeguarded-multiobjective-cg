function out = lov5(x, request, mode)
M = [-1,-0.03,0.011; -0.03,-1,0.07; 0.011,0.07,-1.01];
y1 = [x(1); x(2)-0.15; x(3)];
y2 = [x(1); x(2)+1.1; 0.5*x(3)];
c1 = sqrt(2*pi/0.35);
c2 = sqrt(2*pi/3);
e1 = c1*exp((y1'*M*y1)/0.35^2);
e2 = c2*exp((y2'*M*y2)/3^2);
s = sqrt(2)/2;
if strcmp(request, 'value')
    out = [s*x(1)+s*(e1+e2); -s*x(1)+s*(e1+e2)];
elseif strcmp(mode, 'legacy')
    q11 = (-x(1)-0.03*x(2)+0.0045+0.011*x(3) ...
        -x(1)-0.03*(x(2)-0.15)+0.011*x(3))/0.35^2;
    q12 = (-0.03*x(1)-(x(2)-0.15)-0.03*x(1)-x(2)+0.15 ...
        +0.07*x(3)+0.07*x(3))/0.35^2;
    q13 = (0.011*x(1)+0.07*(x(2)-0.15)-1.01*x(3) ...
        +0.011*x(1)+0.07*x(2)-0.0105-1.01*x(3))/0.35^2;
    q21 = (-x(1)-0.03*x(2)-0.033+0.011*x(3)/2 ...
        -0.03*(x(2)+1.1)+0.011*x(3)/2)/3^2;
    q22 = (-0.03*x(1)-(x(2)+1.1)-0.03*x(1)-x(2)-1.1 ...
        +0.07*x(3)/2+0.07*x(3)/2)/3^2;
    q23 = (0.011*x(1)+0.07*(x(2)+1.1)/2-1.01*x(3)/4 ...
        +0.011*x(1)+0.07*x(2)+0.07-1.01*x(3)/4)/3^2;
    common = s*[e1*q11+e2*q21, e1*q12+e2*q22, e1*q13+e2*q23];
    out = [common+[s,0,0]; common+[-s,0,0]];
else
    grad1 = e1*(2*M*y1)/0.35^2;
    grad2 = diag([1,1,0.5])*e2*(2*M*y2)/3^2;
    common = s*(grad1+grad2)';
    out = [common+[s,0,0]; common+[-s,0,0]];
end
end
