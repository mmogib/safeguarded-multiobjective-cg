function out = slcdt2(x, request, ~)
if strcmp(request, 'value')
    out = [(x(1)-1)^4+sum((x(2:10)-1).^2); ...
           (x(1)+1)^2+(x(2)+1)^4+sum((x(3:10)+1).^2); ...
           (x(1)-1)^2+(x(2)+1)^2+(x(3)-1)^4+ ...
           sum((x(4:2:10)+1).^2)+sum((x(5:2:9)-1).^2)];
else
    out = [[4*(x(1)-1)^3; 2*(x(2:10)-1)]'; ...
           [2*(x(1)+1); 4*(x(2)+1)^3; 2*(x(3:10)+1)]'; ...
           [2*(x(1)-1); 2*(x(2)+1); 4*(x(3)-1)^3; ...
            2*(x(4)+1); 2*(x(5)-1); 2*(x(6)+1); 2*(x(7)-1); ...
            2*(x(8)+1); 2*(x(9)-1); 2*(x(10)+1)]'];
end
end
